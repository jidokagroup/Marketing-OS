import Link from "next/link";
import { notFound } from "next/navigation";
import {
  CalendarClock,
  CheckCircle2,
  CircleCheckBig,
  CopyPlus,
  Edit3,
  Trash2,
} from "lucide-react";

import { requireUser } from "@/lib/auth";
import { decodeEditSignal } from "@/lib/edit-signals";
import { SeatSync } from "@/components/seat-context";
import { CopyButton } from "@/components/copy-button";
import { LearnFromEditPrompt } from "@/components/learn-from-edit-prompt";
import { ScoreBadge } from "@/components/score-badge";
import { ConfirmSubmitButton } from "@/components/confirm-submit-button";
import { Badge } from "@/components/ui/badge";
import { Button, ButtonLink } from "@/components/ui/button";
import {
  Card,
  CardContent,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";
import { Textarea } from "@/components/ui/textarea";
import {
  Tabs,
  TabsContent,
  TabsList,
  TabsTrigger,
} from "@/components/ui/tabs";
import {
  deleteGeneratedContentAction,
  duplicateGeneratedContentAction,
  toggleApprovalAction,
  updateGeneratedContentAction,
} from "../actions";
import { GenerationStatusBanner } from "./GenerationStatusBanner";
import { PrimaryScriptTab } from "./PrimaryScriptTab";
import { SavedToast } from "./SavedToast";

const SCORE_FIELDS: { key: string; label: string }[] = [
  { key: "voice_match", label: "Voice" },
  { key: "syntax_match", label: "Syntax" },
  { key: "hook_match", label: "Hook" },
  { key: "story_match", label: "Story" },
  { key: "belief_match", label: "Belief" },
  { key: "emotional_match", label: "Emotional" },
  { key: "phrase_match", label: "Phrase" },
  { key: "brand_accuracy", label: "Brand" },
  { key: "knowledge_accuracy", label: "Knowledge" },
];

export default async function GeneratedDetailPage({
  params,
  searchParams,
}: {
  params: Promise<{ id: string }>;
  searchParams: Promise<{ saved?: string; learn?: string }>;
}) {
  const { id } = await params;
  const { saved, learn } = await searchParams;
  const { supabase } = await requireUser();

  const { data: content } = await supabase
    .from("marketing_os_generated_content")
    .select("*")
    .eq("id", id)
    .maybeSingle();

  if (!content) notFound();

  const { data: agent } = await supabase
    .from("marketing_os_writing_agents")
    .select("id, name, client_id")
    .eq("id", content.agent_id)
    .maybeSingle();

  const { data: score } = await supabase
    .from("marketing_os_quality_scores")
    .select("*")
    .eq("generated_content_id", id)
    .order("attempt", { ascending: false })
    .limit(1)
    .maybeSingle();

  const { data: scheduledPosts } = await supabase
    .from("marketing_os_scheduled_posts")
    .select("id, status, platform")
    .eq("generated_content_id", id);
  const scheduledStatus = scheduledPosts?.[0]?.status ?? "draft";
  const isApproved = Boolean(content.approved_at);
  // Matches the /generated library's libraryStatus() precedence: a quality
  // flag always surfaces first, even over scheduled/published, so a review
  // note never gets buried once something is queued.
  const approvalStatus = content.below_threshold
    ? "Needs revision"
    : scheduledStatus === "posted"
      ? "Published"
      : scheduledStatus === "scheduled"
        ? "Approved and scheduled"
        : isApproved
          ? "Approved"
          : "Draft review";

  const isPending = content.status === "queued" || content.status === "running";
  const isFallback = !isPending && content.model === "fallback-template";
  const platformText = String(content.platform ?? "").toLowerCase();
  const wantsBlogPost = platformText.includes("blog");
  const agentId = agent?.id ?? "";
  const baseSchedulerParams: Record<string, string> = {
    agent_id: agentId,
    content_id: content.id,
  };
  if (agent?.client_id) baseSchedulerParams.client = agent.client_id;

  function scheduleHref(field: string, title: string) {
    const params = new URLSearchParams({
      ...baseSchedulerParams,
      title,
      content_field: field,
    });
    return `/scheduler?${params.toString()}`;
  }

  const regenerateHref = agent
    ? `/agents/${agent.id}?tab=generate&${new URLSearchParams({
        title: content.title ?? "",
        topic: content.topic ?? "",
        goal: content.goal ?? "",
        notes: content.notes ?? "",
      }).toString()}`
    : undefined;

  const variants: {
    value: string;
    label: string;
    text: string | null;
    field?: string;
    disabled?: boolean;
    disabledNote?: string;
  }[] = [
    {
      value: "primary",
      label: "Short form script",
      text: content.primary_script,
      field: "primary_script",
    },
    {
      value: "short",
      label: "Convia content generator",
      text: null,
      disabled: true,
      disabledNote:
        "Platform-specific captions are generated by Convia's content generator as part of the distribution layer, not here.",
    },
    {
      value: "long",
      label: wantsBlogPost ? "Blog post" : "Long caption",
      text: content.long_version,
      field: "long_version",
    },
    {
      value: "organic",
      label: "Convia Carousels",
      text: null,
      disabled: true,
      disabledNote: "Carousel content is generated by Convia as part of the distribution layer, not here.",
    },
    {
      value: "sales",
      label: "Email",
      text: content.sales_version,
      field: "sales_version",
    },
  ];

  const hooks = (content.alternate_hooks ?? []) as string[];
  const ctas = (content.alternate_ctas ?? []) as string[];
  const blogKeywords = (content.blog_keywords ?? []) as string[];
  const blogLinkSuggestions = (content.blog_link_suggestions ?? []) as string[];
  const pieceTitle = content.title || content.topic || "";
  const generatedLibraryHref = agent?.client_id
    ? `/generated?client=${agent.client_id}`
    : "/generated";

  return (
    <div className="mx-auto max-w-4xl">
      <SeatSync agentId={content.agent_id} clientId={agent?.client_id ?? null} />
      <SavedToast variant={saved} />
      {agent && (
        <LearnFromEditPrompt
          agentId={agent.id}
          clientId={agent.client_id}
          contentId={id}
          removedTerms={decodeEditSignal(learn)}
        />
      )}
      <GenerationStatusBanner
        status={content.status}
        errorMessage={content.error_message}
        retryHref={agent ? `/agents/${agent.id}?tab=generate` : undefined}
      />
      <div className="mb-6">
        <Link
          href={generatedLibraryHref}
          className="text-sm text-muted-foreground hover:text-foreground"
        >
          ← All generated content
        </Link>
      </div>

      <div className="mb-6 flex flex-col gap-3 sm:flex-row sm:items-start sm:justify-between">
        <div className="space-y-2">
          {/* Same precedence as the Generated Content list. The detail used to
              lead with the topic while the list led with the title, so the two
              named the same piece differently and neither matched the other in
              an audit trail. */}
          <h1 className="text-2xl font-bold tracking-tight">
            {content.title || content.topic || "Untitled piece"}
          </h1>
          {content.title && content.topic && content.title !== content.topic && (
            <p className="text-sm text-muted-foreground">{content.topic}</p>
          )}
          <div className="flex flex-wrap items-center gap-1.5">
            {agent && (
              <Link href={`/agents/${agent.id}`}>
                <Badge variant="outline">{agent.name}</Badge>
              </Link>
            )}
            {content.platform && <Badge variant="secondary">{content.platform}</Badge>}
            {content.goal && <Badge variant="secondary">{content.goal}</Badge>}
            <Badge variant={scheduledStatus === "draft" ? "outline" : "default"}>
              {scheduledStatus}
            </Badge>
            {isApproved && (
              <Badge variant="default">
                <CircleCheckBig className="mr-1 h-3 w-3" />
                Approved
              </Badge>
            )}
          </div>
        </div>
        <div className="flex flex-wrap items-center gap-2">
          {content.overall_score != null && (
            <div className="flex items-center gap-2">
              <span className="text-sm text-muted-foreground">Authenticity</span>
              <ScoreBadge score={Number(content.overall_score)} />
            </div>
          )}
          {!isPending && (
            <form action={toggleApprovalAction}>
              <input type="hidden" name="id" value={content.id} />
              <input
                type="hidden"
                name="currently_approved"
                value={isApproved ? "1" : "0"}
              />
              <Button
                type="submit"
                variant={isApproved ? "outline" : "default"}
                size="sm"
              >
                <CircleCheckBig className="mr-1 h-3.5 w-3.5" />
                {isApproved ? "Unapprove" : "Approve"}
              </Button>
            </form>
          )}
          {agent && (
            <ButtonLink href={`/agents/${agent.id}?tab=generate`} variant="outline" size="sm">
              Generate another
            </ButtonLink>
          )}
          {!isPending && (
            <form action={duplicateGeneratedContentAction}>
              <input type="hidden" name="id" value={content.id} />
              <Button type="submit" variant="outline" size="sm">
                <CopyPlus className="mr-1 h-3.5 w-3.5" />
                Duplicate
              </Button>
            </form>
          )}
          <form action={deleteGeneratedContentAction}>
            <input type="hidden" name="id" value={content.id} />
            <ConfirmSubmitButton
              title="Delete this generated piece?"
              confirmLabel="Delete piece"
              message={`"${content.title || content.topic || "This piece"}" is deleted permanently, along with its scores and every version of the copy. Scheduled posts made from it keep their captions but lose the link back.`}
              variant="ghost"
              size="sm"
              className="text-muted-foreground hover:text-destructive"
            >
              <Trash2 className="mr-1 h-3.5 w-3.5" />
              Delete
            </ConfirmSubmitButton>
          </form>
        </div>
      </div>

      {!isPending && (
        <Card className="mb-6">
          <CardContent className="grid gap-4 py-4 text-sm md:grid-cols-[1fr_auto]">
            <div className="text-muted-foreground">
              <p>
                The authenticity score estimates how closely this piece matches the
                agent&apos;s voice, beliefs, syntax, hooks, phrases, and brand knowledge.
              </p>
              <p className="mt-1">
                Scores above 90 are usually ready for review and scheduling.
              </p>
            </div>
            <div className="rounded-lg border bg-muted/30 p-3">
              <p className="font-medium">Approval status</p>
              <p className="mt-1 flex items-center gap-2 text-muted-foreground">
                <CheckCircle2 className="h-4 w-4 text-emerald-500" />
                {approvalStatus}
              </p>
            </div>
          </CardContent>
        </Card>
      )}

      {isFallback && (
        <div className="mb-6 rounded-md border border-destructive/30 bg-destructive/5 px-4 py-3 text-sm text-destructive">
          <p>
            <span className="font-medium">This piece is a generic placeholder, not AI-generated content.</span>{" "}
            Claude didn&apos;t return a usable draft, so a template was used instead. Regenerate to get real
            content in this agent&apos;s voice.
          </p>
          {regenerateHref && (
            <ButtonLink href={regenerateHref} size="sm" variant="outline" className="mt-3">
              Regenerate
            </ButtonLink>
          )}
        </div>
      )}

      {content.below_threshold && !isFallback && (
        <div className="mb-6 rounded-md border border-amber-300 bg-amber-50 px-4 py-3 text-sm text-amber-800 dark:border-amber-900 dark:bg-amber-950 dark:text-amber-300">
          This piece scored below the 90 fidelity bar after an automatic rewrite.
          Review carefully before publishing.
        </div>
      )}

      {!isPending && (
      <div className="grid gap-6 lg:grid-cols-3">
        <div className="lg:col-span-2 space-y-6">
          <Card>
            <CardHeader className="flex flex-row items-center justify-between">
              <CardTitle>Content</CardTitle>
            </CardHeader>
            <CardContent>
              <Tabs defaultValue="primary">
                <TabsList>
                  {variants.map((v) => (
                    <TabsTrigger key={v.value} value={v.value} disabled={v.disabled}>
                      {v.label}
                    </TabsTrigger>
                  ))}
                </TabsList>
                {variants.map((v) =>
                  v.disabled ? (
                    <TabsContent key={v.value} value={v.value} className="mt-4">
                      <p className="rounded-md border border-dashed p-4 text-sm text-muted-foreground">
                        {v.disabledNote}
                      </p>
                    </TabsContent>
                  ) : v.value === "primary" ? (
                    <TabsContent key={v.value} value={v.value} className="mt-4">
                      <PrimaryScriptTab
                        contentId={content.id}
                        label={v.label}
                        initialScript={v.text ?? ""}
                        hooks={hooks}
                        ctas={ctas}
                        scheduleHref={v.field ? scheduleHref(v.field, pieceTitle) : undefined}
                      />
                    </TabsContent>
                  ) : (
                    <TabsContent key={v.value} value={v.value} className="mt-4">
                      <form
                        action={updateGeneratedContentAction}
                        className="space-y-4"
                      >
                        <input type="hidden" name="id" value={content.id} />
                        <input type="hidden" name="variant" value={v.value} />
                        <div className="flex justify-end">
                          <CopyButton text={v.text ?? ""} />
                        </div>
                        <Textarea
                          name={`${v.value}_version`}
                          rows={12}
                          className="font-sans text-sm leading-relaxed"
                          defaultValue={v.text ?? ""}
                        />

                        {v.value === "long" && wantsBlogPost && (
                          <div className="space-y-4 rounded-md border p-3">
                            <div className="space-y-2">
                              <label className="text-sm font-medium">Blog CTA</label>
                              <Textarea
                                name="blog_cta"
                                rows={3}
                                defaultValue={content.blog_cta ?? ""}
                              />
                            </div>
                            <div className="space-y-2">
                              <label className="text-sm font-medium">
                                SEO / AEO keywords (one per line)
                              </label>
                              <Textarea
                                name="blog_keywords"
                                rows={6}
                                defaultValue={blogKeywords.join("\n")}
                              />
                            </div>
                            <div className="space-y-2">
                              <label className="text-sm font-medium">
                                Suggested internal links (one per line)
                              </label>
                              <Textarea
                                name="blog_link_suggestions"
                                rows={5}
                                defaultValue={blogLinkSuggestions.join("\n")}
                              />
                            </div>
                          </div>
                        )}

                        {v.value === "sales" && (
                          <div className="space-y-2 rounded-md border p-3">
                            <label className="text-sm font-medium">Email CTA</label>
                            <Textarea
                              name="email_cta"
                              rows={3}
                              defaultValue={content.email_cta ?? ""}
                            />
                          </div>
                        )}

                        <div className="flex flex-wrap items-center gap-2">
                          <Button type="submit" size="sm">
                            <Edit3 className="mr-1 h-4 w-4" />
                            Save {v.label.toLowerCase()}
                          </Button>
                          {v.field && (
                            <ButtonLink
                              href={scheduleHref(v.field, pieceTitle)}
                              variant="outline"
                              size="sm"
                            >
                              <CalendarClock className="mr-1 h-3.5 w-3.5" />
                              Pair with a visual asset + schedule
                            </ButtonLink>
                          )}
                        </div>
                      </form>
                    </TabsContent>
                  ),
                )}
              </Tabs>
            </CardContent>
          </Card>
        </div>

        <div className="space-y-6">
          <Card>
            <CardHeader>
              <CardTitle>Quality scores</CardTitle>
            </CardHeader>
            <CardContent className="space-y-2">
              {score ? (
                <>
                  {SCORE_FIELDS.map((f) => {
                    const value = score[f.key as keyof typeof score];
                    const n = value == null ? 0 : Number(value);
                    return (
                      <div key={f.key} className="flex items-center justify-between text-sm">
                        <span className="text-muted-foreground">{f.label}</span>
                        <span className="font-medium tabular-nums">{Math.round(n)}</span>
                      </div>
                    );
                  })}
                  <div className="mt-3 flex items-center justify-between border-t pt-3 text-sm font-semibold">
                    <span>Overall</span>
                    <span className="tabular-nums">
                      {score.overall == null ? "—" : Math.round(Number(score.overall))}
                    </span>
                  </div>
                  {score.rationale && (
                    <p className="pt-2 text-xs text-muted-foreground">
                      {score.rationale}
                    </p>
                  )}
                </>
              ) : (
                <p className="text-sm text-muted-foreground">No scores recorded.</p>
              )}
            </CardContent>
          </Card>
        </div>
      </div>
      )}
    </div>
  );
}
